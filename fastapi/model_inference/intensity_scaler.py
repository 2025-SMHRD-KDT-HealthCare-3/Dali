# [구간 2] 결과 데이터클래스
# ═══════════════════════════════════════════════
@dataclass
class IntensityResult:
    detected_adverb: str | None    # 감지된 부사 (없으면 None)
    arousal        : float         # 그 부사의 Arousal 값
    temperature    : float         # 계산된 Temperature
    level          : str           # weak / normal / strong / extreme
    scores_before  : dict[str, float]   # 보정 전 점수
    scores_after   : dict[str, float]   # 보정 후 점수 (최종 사용값)


# ── 내부 함수 ─────────────────────────────────────────────────
# ═══════════════════════════════════════════════
# [구간 3] 내부 함수
# ═══════════════════════════════════════════════

def _detect(text: str) -> tuple[str | None, float]:
    """
    한글 어절 단위로 정확히 일치하는 강도 부사만 감지.
    부분 문자열 오탐 방지 (예: "오늘"의 "늘"이 부사 "늘"로 잘못 매칭되는 문제 수정).
    """
    tokens = re.findall(r'[가-힣]+', text)  # 한글 음절 블록 단위로 추출
    found  = [(t, ADVERB_AROUSAL[t]) for t in tokens if t in ADVERB_AROUSAL]
    if not found:
        return None, 0.0
    return max(found, key=lambda x: abs(x[1]))


def _arousal_to_temp(arousal: float) -> float:
    """
    Arousal → Temperature 변환 (클리핑: [0.40, 1.80])
      arousal +1.0  →  T = 0.60  (분포 뾰족)
      arousal  0.0  →  T = 1.00  (변화 없음)
      arousal -0.5  →  T = 1.20  (분포 평탄)
    """
    return float(np.clip(1.0 - arousal * 0.40, 0.40, 1.80))


def _level(arousal: float) -> str:
    if arousal >= 0.50:    return "extreme"
    elif arousal >= 0.20:  return "strong"
    elif arousal >= -0.15: return "normal"
    else:                  return "weak"


def _rescale(scores: dict[str, float], T: float) -> dict[str, float]:
    """softmax 점수에 Temperature 재적용 후 합=100 정규화."""
    emotions = list(scores.keys())
    probs    = np.array([scores[e] / 100.0 for e in emotions], dtype=float)
    log_p    = np.log(probs + 1e-12)
    scaled   = log_p / T
    scaled  -= scaled.max()
    exp_s    = np.exp(scaled)
    new_p    = exp_s / exp_s.sum()
    return {emotions[i]: round(float(new_p[i] * 100), 1) for i in range(len(emotions))}


# ── 퍼블릭 API ────────────────────────────────────────────────
# ═══════════════════════════════════════════════
# [구간 4] 퍼블릭 API
# ═══════════════════════════════════════════════

def scale_by_intensity(
    scores: dict[str, float],
    text  : str,
) -> IntensityResult:
    """
    강도 부사를 감지해 감정 점수를 보정한다.

    Args:
        scores : predict_emotions() 결과 (합=100)
        text   : 원본 사용자 입력 (이전 발화 제외, 현재 발화만)

    Returns:
        IntensityResult.scores_after 가 최종 점수
    """
    adv, arousal = _detect(text)
    T            = _arousal_to_temp(arousal)

    if adv is None:
        return IntensityResult(
            detected_adverb=None, arousal=0.0, temperature=1.0,
            level="normal", scores_before=scores, scores_after=scores,
        )

    return IntensityResult(
        detected_adverb=adv,
        arousal        =arousal,
        temperature    =round(T, 3),
        level          =_level(arousal),
        scores_before  =scores,
        scores_after   =_rescale(scores, T),
    )
